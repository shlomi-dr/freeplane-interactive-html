"""Generate the single-file Python 3 companion distribution."""
import base64
import hashlib
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "dist" / "freeplane-interactive-html.py"
ASSET_NAMES = ("InteractiveHtmlAddon.groovy", "companion-export.groovy", "viewer-template.html")
SOURCE_URL = "https://github.com/shlomi-dr/freeplane-interactive-html"


def main():
    source = (ROOT / "src" / "companion.py").read_text(encoding="utf-8")
    provenance = [f"# Source: {SOURCE_URL}", "# Generated by scripts/package.py; SHA256 source provenance:"]
    for name in ("src/companion.py", "scripts/package.py", *("src/" + name for name in ASSET_NAMES), "LICENSE", "NOTICE"):
        digest = hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
        provenance.append(f"# {name}: {digest}")
    legal = []
    for name in ("LICENSE", "NOTICE"):
        legal.append(f"# {name}")
        legal.extend("# " + line for line in (ROOT / name).read_text(encoding="utf-8").splitlines())
    embedded = {}
    for name in ASSET_NAMES:
        data = (ROOT / "src" / name).read_bytes()
        embedded[name] = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
    mapping = "{\n" + "".join(f"    {name!r}: {value!r},\n" for name, value in embedded.items()) + "}"
    if "ASSETS = {}" not in source:
        raise RuntimeError("launcher template is missing its ASSETS placeholder")
    result = source.replace("ASSETS = {}", "ASSETS = " + mapping, 1)
    result += "\n" + "\n".join(provenance + legal) + "\n"
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(result, encoding="utf-8")
    OUTPUT.chmod(0o755)
    print(f"Built {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes; one Python file)")


if __name__ == "__main__":
    main()
